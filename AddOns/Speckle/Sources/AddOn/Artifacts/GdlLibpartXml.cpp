    std::string SanitizeName(const std::string& input)
    {
        const std::string invalid = "<>:\"/\\|?*";
        std::string out;
        out.reserve(input.size());
        for (const char c : input)
            out.push_back(invalid.find(c) != std::string::npos ? '_' : c);
        return out;
    }

    std::string BuildSymbolXml(const std::vector<XmlMaterial>& materials, const std::vector<XmlMesh>& meshes)
    {
        std::string out;
        out.reserve(64 * 1024);
        out += XML_HEADER;
        for (const auto& m : materials)
            AppendMaterial(out, m);
        out += XML_MID;
        for (const auto& mesh : meshes)
            AppendMesh(out, mesh);
        out += XML_FOOTER;
        return out;
    }
