    // ── formatting helpers (invariant, dot decimal separator) ────────────────

    // C# "{0:F6}" — fixed 6 decimals.
    std::string F6(double v)
    {
        char buf[64];
        std::snprintf(buf, sizeof(buf), "%.6f", v);
        return buf;
    }

    // C# "0.####" — up to 4 decimals, trailing zeros trimmed, no decimal point when integral.
    std::string Coef(double v)
    {
        char buf[64];
        std::snprintf(buf, sizeof(buf), "%.4f", v);
        std::string s = buf;
        while (!s.empty() && s.back() == '0')
            s.pop_back();
        if (!s.empty() && s.back() == '.')
            s.pop_back();
        return s.empty() ? "0" : s;
    }

    void AppendMaterial(std::string& out, const GdlLibpartXml::XmlMaterial& m)
    {
        // Type 1 is the simple definition (n=9): the specular colour and emission
        // parameters are constants or derived, so emission cannot be set. Only the
        // general definition (type 0, n=16) accepts them — so stay on type 1 unless
        // this material actually emits, and existing output is unchanged.
        const bool general = m.hasEmission;
        out += "DEFINE MATERIAL \"" + m.name + "\" " + (general ? "0" : "1") + ",\n";
        out += "        " + Coef(m.r) + ", " + Coef(m.g) + ", " + Coef(m.b) + ",! surface RGB [0.0..1.0]\n";
        out += "        " + Coef(m.ambient) + ", " + Coef(m.diffuse) + ", " + Coef(m.specular) + ", " +
               Coef(m.transparent) + ", ! ambient, diffuse, specular, transparent [0..1]\n";
        out += "        " + std::to_string(m.shining) + ", ! shining [0..100]\n";
        out += "        " + std::to_string(m.transparencyAttenuation) +
               (general ? "," : " ") + " ! transparency attenuation [0..4]\n";
        if (general)
        {
            // The general form requires specular RGB before the emission triplet;
            // white is the neutral choice the simple form already implies.
            out += "        1, 1, 1, ! specular RGB [0.0..1.0]\n";
            out += "        " + Coef(m.emissionR) + ", " + Coef(m.emissionG) + ", " + Coef(m.emissionB) +
                   ", ! emission RGB [0.0..1.0]\n";
            out += "        " + Coef(m.emissionAttenuation) + " ! emission attenuation [0..65.5]\n";
        }
        out += "\n";
    }

    // Mesh → VERT/EDGE/PGON body, porting ArchicadMesh's edge dedup and signed
    // 1-based edge references (the sign carries the polygon loop orientation).
    struct GdlBody
    {
        std::string verts;
        std::vector<std::pair<int, int>> edges; // start, end (0-based verts)
        std::map<std::pair<int, int>, int> edgeLookup;
        std::vector<int> edgeUseCount;
        std::string pgons;

        int AddEdge(int start, int end)
        {
            const auto key = std::make_pair(std::min(start, end), std::max(start, end));
            auto it = edgeLookup.find(key);
            if (it != edgeLookup.end())
            {
                const int index = it->second;
                edgeUseCount[index]++;
                // Ported as-is from ArchicadMesh.AddEdge: a shared edge beyond the
                // first two gets duplicated instead of reused (smooth/hard edge
                // handling placeholder in the original).
                if (static_cast<int>(edges.size()) > 2)
                {
                    edges.emplace_back(start, end);
                    edgeUseCount.push_back(1);
                    return static_cast<int>(edges.size());
                }
                return edges[index].first == start ? index + 1 : -(index + 1);
            }
            edgeLookup[key] = static_cast<int>(edges.size());
            edges.emplace_back(start, end);
            edgeUseCount.push_back(1);
            return static_cast<int>(edges.size());
        }

        void AddPolygon(const std::vector<int>& faceVertices, const std::string& materialName)
        {
            std::vector<int> edgeRefs;
            edgeRefs.reserve(faceVertices.size());
            for (size_t j = 0; j < faceVertices.size(); j++)
            {
                const int start = faceVertices[j];
                const int end = faceVertices[(j + 1) % faceVertices.size()];
                edgeRefs.push_back(AddEdge(start, end));
            }

            pgons += "MATERIAL \"" + materialName + "\"\n";
            pgons += "PGON " + std::to_string(edgeRefs.size()) + ", 0, -1";
            int count = 1;
            for (const int index : edgeRefs)
            {
                if (count % 10 == 0)
                {
                    pgons += ",\n" + std::to_string(index);
                }
                else
                {
                    pgons += ", " + std::to_string(index);
                }
                count++;
            }
            pgons += "\n";
        }
    };

    void AppendMesh(std::string& out, const GdlLibpartXml::XmlMesh& mesh)
    {
        GdlBody body;

        for (size_t i = 0; i + 2 < mesh.vertices.size(); i += 3)
        {
            body.verts += "VERT " + F6(mesh.vertices[i]) + ", " + F6(mesh.vertices[i + 1]) + ", " +
                          F6(mesh.vertices[i + 2]) + "\n";
        }

        const int vertexCount = static_cast<int>(mesh.vertices.size() / 3);
        size_t i = 0;
        while (i < mesh.faces.size())
        {
            int faceSize = mesh.faces[i++];
            if (faceSize < 3)
                faceSize += 3; // legacy 0/1 tri/quad codes
            if (i + static_cast<size_t>(faceSize) > mesh.faces.size())
                break; // malformed tail — stop rather than read out of bounds

            std::vector<int> face(mesh.faces.begin() + i, mesh.faces.begin() + i + faceSize);
            i += faceSize;

            bool valid = true;
            for (const int v : face)
            {
                if (v < 0 || v >= vertexCount)
                {
                    valid = false;
                    break;
                }
            }
            if (!valid)
                continue;

            if (faceSize == 3)
            {
                body.AddPolygon(face, mesh.materialName);
            }
            else
            {
                // Fan-triangulate ngons so every PGON is planar (the desktop
                // service triangulated via MeshTriangulationHelper; a fan is
                // equivalent for convex faces, which display meshes are in practice).
                for (int t = 1; t + 1 < faceSize; t++)
                {
                    body.AddPolygon({ face[0], face[t], face[t + 1] }, mesh.materialName);
                }
            }
        }

        out += body.verts;
        out += "\n";
        for (const auto& e : body.edges)
        {
            out += "EDGE " + std::to_string(e.first + 1) + ", " + std::to_string(e.second + 1) + ", -1, -1, 1\n";
        }
        out += "\n";
        out += body.pgons;
        out += "\nBODY 4\nBASE\n\n";
    }
